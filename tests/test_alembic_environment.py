"""Tests for alembic/env.py and the agreement between the models and the
migrated schema. The schema comes from the real Alembic migrations (see
conftest.py's session-scoped _create_schema fixture), so a model that is not
in line with a migration shows up here before an autogenerated migration
could silently drop what the migrations created."""

from pathlib import Path

import pytest
from alembic.autogenerate import compare_metadata
from alembic.config import Config
from alembic.runtime.migration import MigrationContext

from alembic import command
from app.db.base import Base  # importing it registers every model
from app.db.database import engine

_ALEMBIC_INI = Path(__file__).parent.parent / "alembic.ini"
_BASELINE_REVISION = "6e1829d5f417"


def test_models_match_the_migrated_schema():
    with engine.connect() as connection:
        differences = compare_metadata(
            MigrationContext.configure(connection), Base.metadata
        )

    assert differences == []


def test_env_reads_database_url_from_settings_with_percent_encoding(
    monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
):
    """Offline mode renders SQL without a connection, so only the URL
    handling of env.py is exercised: a percent-encoded credential used to
    crash ConfigParser's interpolation on every migration run."""
    monkeypatch.setenv("DATABASE_URL", "postgresql://user:p%40ss%25word@db.invalid/osa")
    config = Config(str(_ALEMBIC_INI))

    command.upgrade(config, _BASELINE_REVISION, sql=True)

    assert "CREATE TABLE artists" in capsys.readouterr().out
    assert config.get_main_option("sqlalchemy.url") == (
        "postgresql://user:p%40ss%25word@db.invalid/osa"
    )


def test_env_stops_with_the_settings_error_when_database_url_is_missing(
    monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
):
    monkeypatch.delenv("DATABASE_URL")
    config = Config(str(_ALEMBIC_INI))

    with pytest.raises(SystemExit):
        command.upgrade(config, _BASELINE_REVISION, sql=True)

    assert "DATABASE_URL is not set" in capsys.readouterr().err
